const fs = require("fs"), vm = require("vm"), path = require("path");
const html = fs.readFileSync(path.join(__dirname, "../unidades/u03-memoria/visuales/tablas_paginas.html"), "utf8");
const ctx = { module: { exports: {} } }; vm.createContext(ctx); vm.runInContext(/<script id="motor">([\s\S]*?)<\/script>/.exec(html)[1], ctx);
const { calcular, dividir, leerDir } = ctx.module.exports;
let f = 0; const ok = (c, m) => { console.log((c ? "OK   " : "FALLA") + " " + m); if (!c) f++; };
let r = calcular({ bits: 32, logPag: 12, logEnt: 2, logRam: 30, procesos: 1, trozos: 3 });
ok(r.entradas1 === 2**20 && r.tabla1 === 4 * 2**20, "32 bits / 4 KB / 4 B: 2^20 entradas, 4 MB");
ok(r.bitsTP1 === 10 && r.bitsTP2 === 10 && r.bitsDes === 12, "division 10|10|12");
ok(r.tamTabla2 === 4096 && r.trozoBytes === 4 * 2**20 && r.multiProc === 16384, "2 niveles: 4 tablas de 4 KB = 16 KB (proceso de 12 MB del libro)");
ok(r.marcos === 262144 && r.inv === 262144 * 4, "invertida 1 GB / 4 KB = 262.144 entradas");
ok(r.estado === "ok", "4 MB sobre 1 GB = 0,39 % -> ok");
r = calcular({ bits: 32, logPag: 12, logEnt: 2, logRam: 30, procesos: 100, trozos: 3 });
ok(r.estado === "lim", "100 procesos: 400 MB sobre 1 GB -> al limite (39 %)? " + r.frac.toFixed(3));
r = calcular({ bits: 64, logPag: 12, logEnt: 3, logRam: 30, procesos: 1, trozos: 3 });
ok(r.entradas1 === 2**52 && r.tabla1 === 2**55 && r.estado === "sat", "64 bits / 4 KB / 8 B: 2^52 entradas, 32 PB, saturado");
ok(r.marcos === 262144, "invertida con 64 bits sigue siendo 262.144 entradas");
r = calcular({ bits: 64, logPag: 22, logEnt: 3, logRam: 30, procesos: 1, trozos: 3 });
ok(r.entradas1 === 2**42, "64 bits con paginas de 4 MB: 2^42 entradas");
let d = dividir(leerDir("0x00403004"), 10, 10);
ok(d.tp1 === 1 && d.tp2 === 3 && d.d === 4, "0x00403004 -> 1 | 3 | 4 (errata del libro: TP2=2)");
d = dividir(leerDir("0x0080500C"), 10, 10);
ok(d.tp1 === 2 && d.tp2 === 5 && d.d === 12, "0x0080500C -> 2 | 5 | 12");
d = dividir(leerDir("0xFFFFF123"), 10, 10);
ok(d.tp1 === 1023 && d.tp2 === 1023 && d.d === 0x123, "0xFFFFF123 -> 1023 | 1023 | 0x123");
d = dividir(leerDir("0x00001A2B"), 10, 10);
ok(d.tp1 === 0 && d.tp2 === 1 && d.d === 0xA2B, "0x00001A2B -> 0 | 1 | 0xA2B");
ok(leerDir("4206596") === 0x00403004 && leerDir("403004H") === 0x403004, "lectura decimal y H");
ok(!!dividir(5, 20, 20).error && !!dividir(NaN, 10, 10).error, "errores de entrada");
console.log(f ? f + " fallos" : "0 fallos"); process.exit(f ? 1 : 0);
